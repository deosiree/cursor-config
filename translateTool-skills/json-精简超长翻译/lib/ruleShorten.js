/** 短语级替换 */
const PHRASE_SUBS = [
  [/Флаг\s+валидности/gi, 'Флаг валид.'],
  [/Переключение\s+каталога/gi, 'Перекл. кат.'],
  [/Смена\s+каталога/gi, 'См. кат.'],
  [/Информация\s+о\s+файле/gi, 'Инф. о файле'],
  [/Цикл\s+автоматической\s+очистки/gi, 'Цикл авто очистки'],
  [/после\s+тайм-аута/gi, 'посл. тайм-аут'],
  [/Автоматическое\s+сжатие/gi, 'Авто сжатие'],
  [/Очистить\s+версию/gi, 'Очист. вер.'],
  [/Сравнение\s+содержимого\s+и\s+обновление\s+верси(?:й|и)?/gi, 'сравн. содерж. и обнов. вер.'],
  [/Атрибуты\s+переключения\s+каталога/gi, 'атр. перекл. кат.']
];

function applySubs(text, subs) {
  let out = String(text || '');
  for (const [re, rep] of subs) {
    out = out.replace(re, rep);
  }
  return out.replace(/\s{2,}/g, ' ').trim();
}

/**
 * 规则层缩短（可能仍超长）
 * @param {string} text
 * @param {number} [byteLimit]
 * @returns {{ text: string, bytes: number, changed: boolean }}
 */
function ruleShortenRu(text, byteLimit) {
  let out = String(text || '');
  const before = out;
  out = applySubs(out, PHRASE_SUBS);
  out = applySubs(out, WORD_SUBS);
  // 紧凑化：去掉缩写块之间多余空格（实跑 db 对比升版本 2 条）
  out = out
    .replace(/сравн\.\s+содерж\.\s+и\s+обнов\.\s+вер\./gi, 'сравн.содерж.обнов.вер.')
    .replace(/атр\.\s+перекл\.\s+кат\./gi, 'перекл.кат.')
    .replace(/перекл\.\s+кат\./gi, 'перекл.кат.');
  // 删尾部标点省 1B
  out = out.replace(/[!?]+$/u, '');
  return {
    text: out,
    bytes: utf8ByteLen(out),
    changed: out !== before
  };
}

/**
 * 在 byteLimit 内尽量缩短；仍超长则返回最短尝试结果
 */
function ruleShortenToLimit(text, byteLimit) {
  let { text: out, bytes } = ruleShortenRu(text, byteLimit);
  if (bytes <= byteLimit) {
    return { text: out, bytes, ok: true, via: 'rules' };
  }
  // 二次：删括号内英注、压缩空格
  out = out.replace(/\s*\([^)]*[A-Za-z][^)]*\)/g, '').trim();
  bytes = utf8ByteLen(out);
  if (bytes <= byteLimit) {
    return { text: out, bytes, ok: true, via: 'rules_strip_paren' };
  }
  return { text: out, bytes, ok: false, via: 'rules_partial' };
}

function truncateUtf8Boundary(text, byteLimit) {
  let s = String(text || '');
  while (s && utf8ByteLen(s) > byteLimit) {
    s = s.slice(0, -1);
  }
  return s;
}

module.exports = {
  ruleShortenRu,
  ruleShortenToLimit,
  truncateUtf8Boundary,
  WORD_SUBS,
  PHRASE_SUBS
};
