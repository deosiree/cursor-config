def main() -> None:
    with CASES_PATH.open(encoding="utf-8") as f:
        data = json.load(f)

    data["fieldDefaults"].pop("用例结果", None)

    missing = []
    for case in data["cases"]:
        name = case["name"]
        if name == "gateway创建租户返回有效业务错误信息":
            case.clear()
            case.update(GATEWAY_REWRITE)
            continue
        exp = EXPECTED.get(name)
        if exp:
            case["expected"] = exp
        else:
            missing.append(name)

    if missing:
        raise SystemExit(f"缺少 expected 映射: {missing}")

    with CASES_PATH.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Patched {len(data['cases'])} cases in {CASES_PATH}")


if __name__ == "__main__":
    main()
